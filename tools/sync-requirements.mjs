#!/usr/bin/env node
// Roll every app's requirements.txt up into the one at the repo root.
//
//   node tools/sync-requirements.mjs           # rewrite requirements.txt
//   node tools/sync-requirements.mjs --check   # fail if out of date (CI)
//
// Connect Cloud installs the requirements.txt sitting next to the primary
// file, and for the gallery that is the repo root. One app adding a
// dependency and forgetting this step is a deployment that starts and then
// fails on the first visit to that app, which is the worst place to find out.
//
// Each app keeps its own file so it still runs standalone.

import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");

// Kept in step with pyproject.toml, which is what a local checkout installs.
const GALLERY_DEPS = ["shiny>=1.8.0", "shinyreact>=0.1.0", "pyyaml>=6.0"];

function parse(text) {
  return text
    .split("\n")
    .map((line) => line.replace(/#.*$/, "").trim())
    .filter(Boolean);
}

// "shiny>=1.8.0" -> "shiny". Enough to spot the same package pinned twice.
function nameOf(spec) {
  return spec
    .split(/[<>=!~[;]/)[0]
    .trim()
    .toLowerCase()
    .replaceAll("_", "-");
}

let appDirs = [];
try {
  appDirs = (await readdir(path.join(root, "apps"), { withFileTypes: true }))
    .filter((e) => e.isDirectory())
    .map((e) => e.name)
    .sort();
} catch {
  // No apps yet. The gallery dependencies alone are a valid answer.
}

const byName = new Map();
for (const spec of GALLERY_DEPS) byName.set(nameOf(spec), { spec, from: ["gallery"] });

const conflicts = [];
for (const app of appDirs) {
  const file = path.join(root, "apps", app, "requirements.txt");
  let text;
  try {
    text = await readFile(file, "utf8");
  } catch {
    continue;
  }
  for (const spec of parse(text)) {
    const name = nameOf(spec);
    const seen = byName.get(name);
    if (!seen) {
      byName.set(name, { spec, from: [app] });
    } else if (seen.spec !== spec) {
      conflicts.push(`  ${name}: "${seen.spec}" (${seen.from.join(", ")}) vs "${spec}" (${app})`);
    } else {
      seen.from.push(app);
    }
  }
}

if (conflicts.length) {
  console.error("Two apps ask for the same package with different constraints:");
  console.error(conflicts.join("\n"));
  console.error("");
  console.error("One process serves every app, so there is only one version to");
  console.error("install. Agree on a single constraint in both files.");
  process.exit(1);
}

const lines = [...byName.entries()].sort(([a], [b]) => a.localeCompare(b));

const body = [
  "# Generated by tools/sync-requirements.mjs. Do not edit by hand.",
  "#",
  "# Connect Cloud installs this file for the Python gallery deployment. It is",
  "# the union of apps/*/requirements.txt, which is where a dependency belongs,",
  "# because each app has to run on its own too.",
  "#",
  "# Regenerate with: node tools/sync-requirements.mjs",
  "",
  ...lines.map(([, entry]) => `${entry.spec}  # ${entry.from.join(", ")}`),
  "",
].join("\n");

const target = path.join(root, "requirements.txt");
let current = "";
try {
  current = await readFile(target, "utf8");
} catch {
  // First run.
}

if (current === body) {
  console.log("requirements.txt is up to date.");
  process.exit(0);
}

if (check) {
  console.error("requirements.txt is out of date.");
  console.error("Run: node tools/sync-requirements.mjs");
  process.exit(1);
}

await writeFile(target, body);
console.log(`Wrote requirements.txt with ${lines.length} packages from ${appDirs.length} apps.`);
